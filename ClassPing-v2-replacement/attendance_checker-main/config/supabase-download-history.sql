-- ClassPing v2: persistent attendance-download audit history.
-- Safe, additive migration: creates a new table and does not alter classping_state.
-- Run once in Supabase Dashboard > SQL Editor before deploying the updated app.

create table if not exists public.classping_download_history (
  id bigint generated by default as identity primary key,
  downloaded_at timestamptz not null default now(),
  role text not null check (role in ('monitor', 'viewer')),
  format text not null check (format in ('pdf', 'xlsx', 'csv')),
  scope text not null,
  filename text not null,
  record_count integer not null default 0 check (record_count >= 0),
  details jsonb not null default '{}'::jsonb
);

create index if not exists classping_download_history_downloaded_at_idx
  on public.classping_download_history (downloaded_at desc);

alter table public.classping_download_history enable row level security;

-- No direct browser access. Only the server-side Supabase Secret key can access this table.
revoke all on table public.classping_download_history from anon, authenticated;
grant all on table public.classping_download_history to service_role;
grant usage, select on sequence public.classping_download_history_id_seq to service_role;
